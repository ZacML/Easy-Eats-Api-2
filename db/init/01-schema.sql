-- Criação do schema do Easy Eats.
-- Espelha as entidades JPA (pacote com.easyeats.api.entity) e usa IF NOT EXISTS.
-- Executado automaticamente pelo PostgreSQL apenas na PRIMEIRA inicialização
-- (volume de dados vazio). O Hibernate (ddl-auto=update) continua ativo como rede de segurança.

CREATE TABLE IF NOT EXISTS role (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuario (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    password VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    role_id    BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (usuario_id, role_id)
);

CREATE TABLE IF NOT EXISTS tb_categoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    flativo        VARCHAR(255) NOT NULL,
    data_criacao   TIMESTAMP(6) NOT NULL,
    data_alteracao TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS tb_ingrediente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255)  NOT NULL,
    unidade_medida VARCHAR(255)  NOT NULL,
    custo          NUMERIC(10,2) NOT NULL,
    flativo        VARCHAR(1)    NOT NULL,
    data_criacao   TIMESTAMP(6)  NOT NULL,
    data_alteracao TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS tb_estoques (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qtd_atual      INTEGER      NOT NULL,
    qtd_minima     INTEGER      NOT NULL,
    dt_atualizacao TIMESTAMP(6) NOT NULL,
    versao         BIGINT,
    ingrediente_id BIGINT       NOT NULL UNIQUE REFERENCES tb_ingrediente (id)
);

CREATE TABLE IF NOT EXISTS tb_mesa (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero  INTEGER      NOT NULL UNIQUE,
    flativo VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_produto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    descricao      VARCHAR(255),
    data_criacao   TIMESTAMP(6) NOT NULL,
    data_alteracao TIMESTAMP(6),
    flativo        VARCHAR(255) NOT NULL,
    categoria_id   BIGINT       NOT NULL REFERENCES tb_categoria (id)
);

CREATE TABLE IF NOT EXISTS tb_preco (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor          NUMERIC(10,2) NOT NULL,
    data_criacao   TIMESTAMP(6)  NOT NULL,
    data_alteracao TIMESTAMP(6),
    flativo        VARCHAR(255)  NOT NULL,
    produto_id     BIGINT        NOT NULL REFERENCES tb_produto (id)
);

CREATE TABLE IF NOT EXISTS tb_produto_ingrediente (
    produto_id     BIGINT NOT NULL REFERENCES tb_produto (id),
    ingrediente_id BIGINT NOT NULL REFERENCES tb_ingrediente (id),
    quantidade     DOUBLE PRECISION,
    PRIMARY KEY (produto_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS tb_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_criacao   TIMESTAMP(6)  NOT NULL,
    data_alteracao TIMESTAMP(6),
    cliente        VARCHAR(255),
    mesa_id        BIGINT        NOT NULL REFERENCES tb_mesa (id),
    status         VARCHAR(255)  CHECK (status IN ('ABERTO', 'EM_PREPARO', 'FINALIZADO', 'CANCELADO')),
    valor_total    NUMERIC(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade     INTEGER       NOT NULL,
    valor_unitario NUMERIC(10,2) NOT NULL,
    pedido_id      BIGINT        NOT NULL REFERENCES tb_pedido (id),
    produto_id     BIGINT        NOT NULL REFERENCES tb_produto (id)
);

-- Entidade StatusPedido (só id; sem uso no código atual, mantida por fidelidade ao mapeamento).
CREATE TABLE IF NOT EXISTS tb_status_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
