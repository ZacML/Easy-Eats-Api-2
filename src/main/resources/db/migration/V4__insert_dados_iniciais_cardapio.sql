SELECT setval(pg_get_serial_sequence('tb_ingrediente', 'id'), COALESCE((SELECT MAX(id) FROM tb_ingrediente), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('tb_estoques', 'id'),    COALESCE((SELECT MAX(id) FROM tb_estoques), 0) + 1,    false);
SELECT setval(pg_get_serial_sequence('tb_produto', 'id'),     COALESCE((SELECT MAX(id) FROM tb_produto), 0) + 1,     false);
SELECT setval(pg_get_serial_sequence('tb_preco', 'id'),       COALESCE((SELECT MAX(id) FROM tb_preco), 0) + 1,       false);
SELECT setval(pg_get_serial_sequence('tb_mesa', 'id'),        COALESCE((SELECT MAX(id) FROM tb_mesa), 0) + 1,        false);

