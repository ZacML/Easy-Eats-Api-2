-- V3: cria (se necessário) a estrutura de usuários/roles e insere o usuário padrão "superadmin".
-- O Flyway roda ANTES do Hibernate (ddl-auto=update), então as tabelas são criadas aqui
-- com o mesmo desenho das entidades Usuario e Role, para funcionar também em banco novo.

CREATE TABLE IF NOT EXISTS usuario (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    password VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS role (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    role_id    BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (usuario_id, role_id)
);

-- Sincroniza as sequences de id com os dados já existentes (evita "role_pkey" duplicada
-- quando linhas foram inseridas manualmente com id explícito).
SELECT setval(pg_get_serial_sequence('role', 'id'),    COALESCE((SELECT MAX(id) FROM role), 0) + 1,    false);
SELECT setval(pg_get_serial_sequence('usuario', 'id'), COALESCE((SELECT MAX(id) FROM usuario), 0) + 1, false);

